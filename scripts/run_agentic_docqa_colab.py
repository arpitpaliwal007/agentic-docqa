class DriveStore:
    """Persist idle application state without running a live SQLite DB on Drive."""

    STATE_ITEMS = ("data", "qdrant_db", "notebook-session.json", "notebook-account.json", "app.log", "ollama.log")

    def __init__(self, folder: Path):
        self.folder = folder
        self.snapshots = folder / "snapshots"
        self.snapshots.mkdir(parents=True, exist_ok=True)

    def save_source(self):
        source = self.folder / "source" / SOURCE_SHA256
        source.mkdir(parents=True, exist_ok=True)
        archive = source / "project.zip"
        if not archive.exists():
            archive.write_bytes(base64.b64decode(SOURCE_ZIP_BASE64))
        script = Path(__file__).resolve()
        target = self.folder / "run_agentic_docqa_colab.py"
        if script != target.resolve():
            shutil.copy2(script, target)

    def restore(self, root: Path):
        marker = root / ".drive-location.json"
        if marker.exists() and json.loads(marker.read_text()) != str(self.folder):
            raise RuntimeError("This runtime directory belongs to another Drive folder. Choose a new --work-dir.")
        latest = self.folder / "latest.json"
        if latest.exists() and not any(root.joinpath(name).exists() for name in self.STATE_ITEMS):
            record = json.loads(latest.read_text())
            filename = record["filename"]
            if Path(filename).name != filename:
                raise RuntimeError("Invalid Drive checkpoint filename.")
            archive = self.snapshots / filename
            if file_digest(archive) != record["sha256"]:
                raise RuntimeError("Drive checkpoint checksum mismatch; the earlier snapshots are still available.")
            with zipfile.ZipFile(archive) as bundle:
                for item in bundle.infolist():
                    path = PurePosixPath(item.filename)
                    if path.is_absolute() or ".." in path.parts or not path.parts or path.parts[0] not in self.STATE_ITEMS:
                        raise RuntimeError("Unsafe path in Drive checkpoint.")
                    target = root.joinpath(*path.parts)
                    if target.is_symlink() or any(p.is_symlink() for p in target.parents):
                        raise RuntimeError("A checkpoint target is a symlink.")
                bundle.extractall(root)
            print(f"Restored documents, chats and search index from {filename}.", flush=True)
        marker.write_text(json.dumps(str(self.folder)))

    def save(self, root: Path):
        filename = f"state-{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}-{secrets.token_hex(4)}.zip"
        target = self.snapshots / filename
        with tempfile.TemporaryDirectory(prefix="docqa-checkpoint-") as directory:
            staging = Path(directory)
            for name in self.STATE_ITEMS:
                source = root / name
                files = source.rglob("*") if source.is_dir() else [source]
                for item in files:
                    if not item.is_file() or item.is_symlink() or item.name == ".lock" or item.name.endswith(("-wal", "-shm")):
                        continue
                    relative = item.relative_to(root)
                    destination = staging / relative
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    with item.open("rb") as stream:
                        is_database = stream.read(16) == b"SQLite format 3\x00"
                    if is_database:
                        # SQLite's online backup includes committed WAL pages safely.
                        deadline = time.monotonic() + 60
                        def progress(status, remaining, total):
                            if time.monotonic() > deadline:
                                raise TimeoutError("Search-index checkpoint timed out; the previous Drive backup is unchanged.")
                        with sqlite3.connect(item.resolve().as_uri() + "?mode=ro", uri=True) as src:
                            with sqlite3.connect(destination) as dst:
                                src.backup(dst, pages=256, progress=progress)
                    else:
                        shutil.copy2(item, destination)
            local_archive = staging / "checkpoint.zip"
            with zipfile.ZipFile(local_archive, "w", compression=zipfile.ZIP_DEFLATED, allowZip64=True) as bundle:
                for item in sorted(staging.rglob("*")):
                    if item.is_file() and item != local_archive:
                        bundle.write(item, item.relative_to(staging).as_posix())
            temporary = target.with_suffix(".partial")
            shutil.copyfile(local_archive, temporary)
            digest = file_digest(local_archive)
            if file_digest(temporary) != digest:
                raise RuntimeError("The Drive checkpoint upload did not verify; the previous backup is unchanged.")
            temporary.replace(target)
            manifest = self.folder / "latest.json.partial"
            manifest.write_text(json.dumps({"filename": filename, "sha256": digest}, indent=2))
            manifest.replace(self.folder / "latest.json")
        return target


def file_digest(path: Path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def mount_storage(folder: Path):
    from google.colab import drive
    drive.mount("/content/drive")
    my_drive = Path("/content/drive/MyDrive")
    if not my_drive.is_dir():
        raise RuntimeError("Google Drive is not mounted. Complete Colab's authorization prompt and rerun.")
    folder = folder.resolve()
    if not folder.is_relative_to(my_drive.resolve()):
        raise ValueError("--drive-dir must be a folder inside /content/drive/MyDrive.")
    store = DriveStore(folder)
    store.save_source()
    return store


def migrate_notebook_account(root: Path):
    """Retain a pre-Drive runner's generated account when its cookie later expires."""
    account_file = root / "notebook-account.json"
    session_file = root / "notebook-session.json"
    sessions_file = root / "data" / "sessions.json"
    users_file = root / "data" / "users.json"
    if account_file.exists() or not all(p.exists() for p in (session_file, sessions_file, users_file)):
        return
    cookies = json.loads(session_file.read_text()).get("cookies", {})
    sessions = json.loads(sessions_file.read_text())
    username = sessions.get(cookies.get("docqa_session"), {}).get("user", "")
    users = json.loads(users_file.read_text())
    if not username.startswith("colab_") or username not in users:
        raise RuntimeError("Cannot identify the older notebook account. Existing data has been preserved.")
    account = {"username": username, "password": secrets.token_urlsafe(24)}
    password_hash = subprocess.run(
        [sys.executable, "-c", "import bcrypt,sys; print(bcrypt.hashpw(sys.stdin.buffer.read(), bcrypt.gensalt()).decode())"],
        input=account["password"], text=True, capture_output=True, check=True,
    ).stdout.strip()
    # Save credentials before updating the generated account's hash; never print them.
    fd = os.open(account_file, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as output:
        json.dump(account, output)
    users[username]["hash"] = password_hash
    temporary = users_file.with_suffix(".tmp")
    temporary.write_text(json.dumps(users, indent=1))
    temporary.replace(users_file)


def unpack_project(destination: Path) -> None:
    destination = destination.resolve()
    raw = base64.b64decode(SOURCE_ZIP_BASE64)
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("The bundled project checksum does not match.")
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        entries = archive.infolist()
        for entry in entries:
            path = PurePosixPath(entry.filename)
            if path.is_absolute() or ".." in path.parts or ".git" in path.parts:
                raise RuntimeError(f"Unsafe bundled path: {entry.filename}")
            target = destination.joinpath(*path.parts)
            if target.is_symlink() or any(p.is_symlink() for p in target.parents):
                raise RuntimeError(f"Refusing a symlink: {target}")
            if target.is_file() and target.read_bytes() != archive.read(entry):
                raise RuntimeError(f"Existing source was changed: {target}. Use a new --work-dir.")
        for entry in entries:
            target = destination / entry.filename
            if entry.is_dir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(archive.read(entry))


def read_json(url: str, payload=None, timeout=10):
    data = None if payload is None else json.dumps(payload).encode()
    request = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return json.load(response)


def available(url: str) -> bool:
    try:
        return bool(read_json(url, timeout=2))
    except (OSError, ValueError, urllib.error.URLError):
        return False


def wait_for(url: str, process: subprocess.Popen, log: Path, timeout=180) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise RuntimeError(f"Service exited. Last log lines:\n{log.read_text(errors='replace')[-6000:]}")
        if available(url):
            return
        time.sleep(1)
    raise RuntimeError(f"Service did not become ready. Check {log}.")


def launch(command, directory: Path, environment: dict, log: Path):
    with log.open("a") as output:
        return subprocess.Popen(command, cwd=directory, env=environment,
                                stdout=output, stderr=subprocess.STDOUT, start_new_session=True)


def pull_model(name: str, ollama_url: str) -> None:
    print(f"Downloading/checking model: {name}", flush=True)
    request = urllib.request.Request(
        f"{ollama_url}/api/pull", data=json.dumps({"name": name, "stream": True}).encode(),
        headers={"Content-Type": "application/json"},
    )
    last_progress = -10
    last_status = ""
    with urllib.request.urlopen(request, timeout=900) as response:
        for line in response:
            event = json.loads(line)
            if event.get("error"):
                raise RuntimeError(event["error"])
            total = event.get("total", 0)
            if total:
                progress = int(100 * event.get("completed", 0) / total)
                if progress < last_progress:
                    last_progress = -10
                if progress >= last_progress + 10:
                    print(f"  {event.get('status', 'downloading')}: {progress}%", flush=True)
                    last_progress = progress
            elif event.get("status") != last_status:
                last_status = event.get("status", "")
                print(f"  {last_status}", flush=True)


class DocQA:
    """Notebook client for the unchanged application's document and chat APIs."""

    def __init__(self, base_url: str, root: Path, processes: list, storage=None):
        import requests

        self.session = requests.Session()
        self.base_url = base_url
        self.root = root
        self.processes = processes
        self.storage = storage
        self.chat_id = None
        session_file = root / "notebook-session.json"
        if session_file.exists():
            self.session.cookies.update(json.loads(session_file.read_text())["cookies"])
        if self.session.get(f"{base_url}/api/chats", timeout=30).status_code == 401:
            account_file = root / "notebook-account.json"
            existing_account = account_file.exists()
            account = json.loads(account_file.read_text()) if existing_account else {
                "username": f"colab_{secrets.token_hex(5)}", "password": secrets.token_urlsafe(24),
            }
            self.session.cookies.clear()
            response = self.session.post(
                f"{base_url}/{'login' if existing_account else 'register'}", data=account,
                timeout=30, allow_redirects=False,
            )
            response.raise_for_status()
            if not self.session.cookies:
                raise RuntimeError("Could not sign into the saved notebook account. Your Drive backups are unchanged.")
            fd = os.open(account_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w") as output:
                json.dump(account, output)
            fd = os.open(session_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w") as output:
                json.dump({"cookies": self.session.cookies.get_dict()}, output)
        state = self._request("GET", "/api/chats")
        self.chat_id = state["selected"]
        self.save(quiet=True)

    def _request(self, method, path, **kwargs):
        response = self.session.request(method, self.base_url + path, timeout=1800, **kwargs)
        if not response.ok:
            raise RuntimeError(f"DocQA returned HTTP {response.status_code}: {response.text[:1500]}")
        result = response.json()
        if method.upper() in {"POST", "PATCH", "DELETE"}:
            self.save(quiet=True)
        return result

    def upload(self, path=None):
        """Select files in Colab, or index a file that already exists in the runtime."""
        if path is None:
            from google.colab import files
            uploaded = files.upload()
        else:
            source = Path(path)
            uploaded = {source.name: source.read_bytes()}
        results = []
        for name, contents in uploaded.items():
            print(f"Indexing {name} (first use may download the BM25 model)...", flush=True)
            result = self._request("POST", "/api/documents", files={"files": (name, contents)})
            for added in result["added"]:
                print(f"  Ready: {added['name']} — {added['children']} searchable chunks")
            for error in result["errors"]:
                print(f"  Failed: {error['name']} — {error['error']}")
            results.append(result)
        return results

    def documents(self):
        return self._request("GET", "/api/documents")

    def new_chat(self):
        self.chat_id = self._request("POST", "/api/chats")["id"]
        return self.chat_id

    def ask(self, question: str):
        """Show agent steps and its answer, and return the answer as a string."""
        if not question.strip():
            raise ValueError("Enter a nonempty question.")
        event = ""
        answer = None
        with self.session.post(
            f"{self.base_url}/api/chats/{self.chat_id}/stream", json={"text": question},
            stream=True, timeout=(15, 1800),
        ) as response:
            response.raise_for_status()
            for line in response.iter_lines(chunk_size=1, decode_unicode=True):
                if line.startswith("event: "):
                    event = line[7:]
                elif line.startswith("data: "):
                    value = json.loads(line[6:])
                    if event == "step":
                        print(f"  Agent: {value}", flush=True)
                    elif event == "answer":
                        answer = value
                    elif event == "error":
                        raise RuntimeError(f"Agent error: {value}. Check {self.root / 'app.log'}.")
        if answer is None:
            raise RuntimeError("The agent finished without an answer. Check app.log.")
        from IPython.display import Markdown, display
        display(Markdown(answer))
        self.save(quiet=True)
        return answer

    def save(self, quiet=False):
        """Save documents, chats, the SQLite index and account state to Drive."""
        if self.storage is None:
            return None
        target = self.storage.save(self.root)
        if not quiet:
            print(f"Saved to Google Drive: {target}")
        return str(target)

    def stop(self):
        for process in reversed(self.processes):
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait(timeout=10)
        self.save()
        print("Stopped the services started by this run.")


def start(args) -> DocQA:
    try:
        import google.colab  # noqa: F401
    except ImportError:
        raise RuntimeError("Upload this file to Google Colab, then run it with %run.") from None
    root = Path(args.work_dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    if available(f"http://127.0.0.1:{args.port}/health"):
        raise RuntimeError("DocQA is already running. Call docqa.stop() before starting this updated file.")
    gpu = shutil.which("nvidia-smi")
    check = None if not gpu else subprocess.run(
        [gpu, "--query-gpu=name,memory.total", "--format=csv,noheader"], capture_output=True, text=True,
    )
    has_gpu = check is not None and check.returncode == 0 and bool(check.stdout.strip())
    if not has_gpu and not args.allow_cpu:
        raise RuntimeError("No GPU detected. Choose Runtime > Change runtime type > GPU, then rerun.")
    print(f"GPU: {check.stdout.strip()}" if has_gpu else "CPU mode: inference will be slower.", flush=True)
    storage = mount_storage(Path(args.drive_dir))
    storage.restore(root)
    cache = storage.folder / "cache"
    cache.mkdir(exist_ok=True)
    environment = os.environ.copy()
    environment.update({"HF_HOME": str(cache / "huggingface"),
                        "SENTENCE_TRANSFORMERS_HOME": str(cache / "sentence-transformers"),
                        "FASTEMBED_CACHE_PATH": str(cache / "fastembed"),
                        "PIP_CACHE_DIR": str(cache / "pip")})
    project = root / "source" / SOURCE_SHA256
    unpack_project(project)
    print("Installing project dependencies...", flush=True)
    subprocess.run([
        sys.executable, "-m", "pip", "install", "--disable-pip-version-check",
        "-r", str(project / "requirements.txt"),
    ], check=True, env=environment)
    migrate_notebook_account(root)

    # Separate port ensures an older server cannot silently use an ephemeral model directory.
    ollama_url = "http://127.0.0.1:11435"
    base_url = f"http://127.0.0.1:{args.port}"
    processes = []
    try:
        if not available(f"{ollama_url}/api/tags"):
            if not shutil.which("ollama"):
                print("Installing Ollama from its official installer...", flush=True)
                subprocess.run(["apt-get", "update", "-qq"], check=True)
                subprocess.run(["apt-get", "install", "-y", "-qq", "zstd"], check=True)
                installer = root / "install-ollama.sh"
                urllib.request.urlretrieve("https://ollama.com/install.sh", installer)
                subprocess.run(["sh", str(installer)], check=True)
            # Some runtimes start Ollama automatically during installation.
            if not available(f"{ollama_url}/api/tags"):
                environment.update({"OLLAMA_HOST": "127.0.0.1:11435", "OLLAMA_CONTEXT_LENGTH": "8192",
                                    "OLLAMA_NUM_PARALLEL": "1", "OLLAMA_MAX_LOADED_MODELS": "2",
                                    "OLLAMA_MODELS": str(storage.folder / "models" / "ollama")})
                log = root / "ollama.log"
                process = launch([shutil.which("ollama"), "serve"], project, environment, log)
                processes.append(process)
                wait_for(f"{ollama_url}/api/tags", process, log)
        pull_model(args.model, ollama_url)
        pull_model("nomic-embed-text", ollama_url)
        print("Warming up the language model...", flush=True)
        read_json(f"{ollama_url}/api/generate", {
            "model": args.model, "prompt": "Reply with OK.", "stream": False, "keep_alive": "30m",
            "options": {"num_predict": 8, "num_ctx": 8192},
        }, timeout=600)
        running = read_json(f"{ollama_url}/api/ps").get("models", [])
        model_info = next((m for m in running if m.get("name") == args.model or m.get("model") == args.model), None)
        if has_gpu and (model_info is None or not model_info.get("size_vram")):
            raise RuntimeError("Ollama did not load the model onto the GPU. Check ollama.log and the GPU driver.")
        if model_info:
            print(f"Model GPU memory: {model_info.get('size_vram', 0) / 1024**3:.2f} GB", flush=True)

        if available(f"{base_url}/health"):
            raise RuntimeError(f"Port {args.port} is already in use. Stop the earlier docqa client or choose --port 8001.")
        environment.update({
            "HOST": "127.0.0.1", "PORT": str(args.port), "RELOAD": "false", "PYTHONUNBUFFERED": "1",
            "LLM_BASE_URL": f"{ollama_url}/v1", "LLM_API_KEY": "ollama", "LLM_MODEL": args.model,
            "OLLAMA_HOST": ollama_url, "DENSE_MODEL": "nomic-embed-text", "DENSE_DIM": "768",
            "QDRANT_URL": "", "QDRANT_PATH": str(root / "qdrant_db"), "DATA_DIR": str(root / "data"),
            "RERANKER": "cross_encoder", "LANGFUSE_ENABLED": "false",
        })
        log = root / "app.log"
        process = launch([sys.executable, "run.py"], project, environment, log)
        processes.append(process)
        wait_for(f"{base_url}/health", process, log, timeout=300)
        client = DocQA(base_url, root, processes, storage)
        print("\nDocQA is ready. In the next notebook cells run:")
        print('  docqa.upload()\n  answer = docqa.ask("Summarize my document")')
        print(f"\nGoogle Drive folder: {storage.folder}")
        print("Documents, chats and the search index are backed up after each upload or question.")
        print("Source, model caches and logs are also saved. Python packages are reinstalled on a fresh runtime.")
        return client
    except BaseException:
        for process in reversed(processes):
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    process.kill()
        raise


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--work-dir", default=str(ROOT), help="Runtime directory for source, models' logs and data")
    parser.add_argument("--drive-dir", default=str(DRIVE_ROOT), help="Persistent Google Drive folder")
    parser.add_argument("--model", default="qwen2.5:7b", help="Ollama model with tool calling (default: qwen2.5:7b)")
    parser.add_argument("--port", default=8000, type=int, help="Local backend port")
    parser.add_argument("--allow-cpu", action="store_true", help="Explicitly allow slower execution without a GPU")
    return parser.parse_args(argv)


if __name__ == "__main__":
    docqa = start(parse_args())
